  'private',
  'public',
  'unlisted'
);

CREATE TYPE "order_status" AS ENUM (
  'pending',
  'confirmed',
  'completed',
  'cancelled',
  'refunded'
);

CREATE TYPE "payment_status" AS ENUM (
  'pending',
  'successful',
  'failed',
  'refunded'
);

